    std::vector<std::string> getGlyph(char c) {
        for (const auto& e : kTable) {
            if (e.ch == c) {
                std::vector<std::string> rows;
                rows.reserve(GLYPH_HEIGHT);
                for (int r = 0; r < GLYPH_HEIGHT; ++r)
                    rows.emplace_back(e.rows[r]);
                return rows;
            }
        }
        // Unknown character -> blank glyph
        return std::vector<std::string>(GLYPH_HEIGHT, std::string(GLYPH_WIDTH, ' '));
    }

    std::vector<std::string> renderString(const std::string& text) {
        std::vector<std::string> rows(GLYPH_HEIGHT, "");
        for (char c : text) {
            auto glyph = getGlyph(c);
            for (int r = 0; r < GLYPH_HEIGHT; ++r) {
                rows[r] += glyph[r];
                rows[r] += ' ';   // 1-column gap between glyphs
            }
        }
        return rows;
    }

